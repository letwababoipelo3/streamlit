"""## Section A-E"""

#a3
import streamlit as st
#b1
import pandas as pd
#c3
st.set_page_config(page_title="CSV Data Explorer", layout="wide")
#d2
st.title("CSV Data Explorer")
#e1
uploaded_file = st.file_uploader("Upload CSV", type=["csv"])

"""##Setion F indent G,H, I, J, K,N

"""

# F-2
if uploaded_file is not None:
  #g4
  df = pd.read_csv(uploaded_file)
  # H-1
  st.dataframe(df.head(5))
  # I-3
  st.metric("Rows", len(df))
  # J-2
  column = st.selectbox("Column", options=df.columns.tolist())
  # K-4
  filter_enabled = st.checkbox("Enable filter", value=False)
  # N-2
  filtered = df.copy()
  #SECTION LMO
  if filter_enabled:
# L-1
   choices = sorted(df[column].dropna().astype(str).unique().tolist())
# M-3
   selected = st.multiselect("Values", options=choices, default=choices)
# O-4
   filtered = filtered[filtered[column].astype(str).isin(selected)]
   #SECTION PQRST
   # P-1
  st.dataframe(filtered)
# Q-3
  st.metric("Filtered rows", filtered.shape[0])
# R-3
  counts = filtered[column].fillna("Missing").astype(str).value_counts()
# S-2
  st.bar_chart(counts)
# T-1
  st.download_button("Download CSV", filtered.to_csv(index=False), file_name="filtered.csv", mime="text/csv")
